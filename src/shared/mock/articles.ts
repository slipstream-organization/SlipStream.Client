export interface ArticleSpec {
  author: NewsAuthor;
  tags: string[];
  relatedTeamIds?: TeamId[];
  lead: string;
  /** quotes[0] is shown on the article cover */
  quotes: NewsQuote[];
  /** paragraphs — joined with blank lines into NewsItem.body */
  build: (c: ArticleContext) => string[];
}

// ── authoring helpers: every block is one plain paragraph ──
const P = (text: string) => text;
const lowerFirst = (t: string) => (t.charAt(0).toLowerCase() + t.slice(1)).replace(': ', ' — ');
/** a list written as one sentence: "Lead-in: a; b; c." (items that are full sentences just follow each other) */
const L = (leadIn: string, items: string[]) =>
  items.every((t) => /[.!?]$/.test(t)) ? items.join(' ') : `${leadIn}: ${items.map(lowerFirst).join('; ')}.`;
const editorial = (text: string, author = DESK.name, role = 'Колонка редакції'): NewsQuote => ({ text, author, role });

